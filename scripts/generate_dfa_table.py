"""Generate docs/dfa_table.md from core.dfa_definition.

Outputs the formal state transition table and 5-tuple definition.
"""

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from core.dfa_definition import (
    ACCEPTING_STATES,
    DELTA,
    START_STATE,
    STATES,
)


def generate_table_markdown() -> str:
    lines = [
        "# Minimal DFA Formal State Transition Table",
        "",
        '> **Target Pattern:** `[A-Za-z]+ing` (English words ending in "ing", length >= 4)  ',
        "> **Source of Truth:** `core/dfa_definition.py`  ",
        "> **Generated by:** `scripts/generate_dfa_table.py`",
        "",
        "---",
        "",
        "## 1. Formal 5-Tuple Definition",
        "",
        "$$M = (Q, \\Sigma, \\delta, q_0, F)$$",
        "",
        "- **$Q$ (State Set):** `{ q0, q1, q2, q3, q4, q_trap }`",
        "- **$\\Sigma$ (Alphabet Classes):** `{ I, N, G, OTHER_LETTER, NON_LETTER }`",
        "- **$q_0$ (Start State):** `q0`",
        "- **$F$ (Accepting States):** `{ q4 }`",
        "- **$\\delta$ (Transition Function):** $Q \\times \\Sigma \\to Q$ (detailed below)",
        "",
        "---",
        "",
        "## 2. Alphabet Equivalence Classes ($\\Sigma$)",
        "",
        "| Class Key | Description | Character Range / Matching Elements |",
        "|---|---|---|",
        "| `I` | Letters 'i' and 'I' | `{'i', 'I'}` |",
        "| `N` | Letters 'n' and 'N' | `{'n', 'N'}` |",
        "| `G` | Letters 'g' and 'G' | `{'g', 'G'}` |",
        "| `OTHER_LETTER` | Any other alphabetic character | `[A-Za-z] \\ {i, I, n, N, g, G}` |",
        "| `NON_LETTER` | Delimiters, whitespace, digits, punctuation | `[^A-Za-z]` |",
        "",
        "---",
        "",
        "## 3. State Definitions and Semantics ($Q$)",
        "",
        "| State ID | Type | Meaning in Plain Words |",
        "|:---:|:---:|---|",
    ]

    for sid in ["q0", "q1", "q2", "q3", "q4", "q_trap"]:
        st = STATES[sid]
        st_type = (
            "Start"
            if st["is_start"]
            else ("**Accepting**" if st["is_accepting"] else "Normal")
        )
        if sid == "q_trap":
            st_type = "Dead / Trap"
        lines.append(f"| `{sid}` | {st_type} | {st['meaning']} |")

    lines.extend(
        [
            "",
            "---",
            "",
            "## 4. State Transition Table ($\\delta$)",
            "",
            "| Current State | Input `I` (`i`/`I`) | Input `N` (`n`/`N`) | Input `G` (`g`/`G`) | Input `OTHER_LETTER` | Input `NON_LETTER` | State Status |",
            "|:---:|:---:|:---:|:---:|:---:|:---:|:---:|",
        ]
    )

    for sid in ["q0", "q1", "q2", "q3", "q4", "q_trap"]:
        row = DELTA[sid]
        status = (
            "**ACCEPTING**"
            if sid in ACCEPTING_STATES
            else ("START" if sid == START_STATE else "-")
        )
        lines.append(
            f"| `{sid}` | `{row['I']}` | `{row['N']}` | `{row['G']}` | `{row['OTHER_LETTER']}` | `{row['NON_LETTER']}` | {status} |"
        )

    lines.extend(
        [
            "",
            "---",
            "",
            "## 5. Lexical Tokenization & Boundary Invariant",
            "",
            "During natural language text scanning, words are demarcated by non-alphanumeric boundaries:",
            "- **Boundary Invariant:** A valid extracted word must neither be preceded nor followed by an alphanumeric character or underscore (`[A-Za-z0-9_]`).",
            "- **Acceptance Invariant:** An extracted word must end at state `q4`, guaranteeing that the token has length $\\ge 4$ and ends in the letters `ing`.",
        ]
    )

    return "\n".join(lines) + "\n"


def main() -> None:
    docs_dir = PROJECT_ROOT / "docs"
    docs_dir.mkdir(parents=True, exist_ok=True)

    table_md = generate_table_markdown()
    table_path = docs_dir / "dfa_table.md"
    table_path.write_text(table_md, encoding="utf-8")
    print(f"Generated DFA table documentation at: {table_path}")


if __name__ == "__main__":
    main()
