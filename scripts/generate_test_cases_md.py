"""Script to generate tests/test_cases.md by executing test suite inputs against RE engine.

Produces a structured Markdown table:
| Pattern | Input | Expected | Observed | Pass/Fail | Description |
"""

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from core.patterns import PATTERNS, get_compiled_pattern
from tests.test_data import TEST_CASES


def generate_markdown() -> str:
    lines = [
        "# Formal Test Cases & Verification: RE Engine (Stage 1)",
        "",
        "> **Project:** Web Content Analyzer: RE vs DFA  ",
        "> **Generated by:** `scripts/generate_test_cases_md.py`  ",
        "> **Status:** Automated Test Run Verification",
        "",
        "## Summary of Target Patterns & Formal Specifications",
        "",
        "| Pattern Key | Label | Formal Regular Expression | Flags |",
        "|---|---|---|---|",
    ]

    for key, p in PATTERNS.items():
        escaped_regex = p["regex"].replace("|", "\\|")
        flags_str = "re.IGNORECASE" if p["flags"] else "None"
        lines.append(f"| `{key}` | {p['label']} | `{escaped_regex}` | `{flags_str}` |")

    lines.extend(
        [
            "",
            "## Test Execution Results",
            "",
            "| Pattern | Input | Expected | Observed | Pass/Fail | Description |",
            "|---|---|---|---|---|---|",
        ]
    )

    total_tests = 0
    passed_tests = 0

    for pattern_key, cases in TEST_CASES.items():
        compiled_re = get_compiled_pattern(pattern_key)
        for c in cases:
            total_tests += 1
            input_val = c["input"]
            expected = c["expected"]
            desc = c.get("desc", "")

            matches = list(compiled_re.finditer(input_val))
            is_match = len(matches) > 0

            # Determine pass/fail
            passed = is_match == expected
            if passed:
                passed_tests += 1
                status = "**PASS**"
            else:
                status = "**FAIL**"

            expected_str = "Match" if expected else "No Match"
            if is_match:
                observed_str = f"Match (`{matches[0].group(0)}`)"
            else:
                observed_str = "No Match"

            # Escape pipes in input for markdown table
            safe_input = input_val.replace("|", "\\|")
            safe_desc = desc.replace("|", "\\|")

            lines.append(
                f"| `{pattern_key}` | `{safe_input}` | {expected_str} | {observed_str} | {status} | {safe_desc} |"
            )

    lines.extend(
        [
            "",
            "## Test Statistics",
            "",
            f"- **Total Test Cases:** {total_tests}",
            f"- **Passed:** {passed_tests}",
            f"- **Failed:** {total_tests - passed_tests}",
            f"- **Pass Rate:** {(passed_tests / total_tests) * 100:.1f}%",
            "",
            "All test cases strictly conform to the 4+ positive and 4+ negative criteria specified in Stage 1 requirements.",
        ]
    )

    return "\n".join(lines) + "\n"


def main():
    md_content = generate_markdown()
    target_path = PROJECT_ROOT / "tests" / "test_cases.md"
    target_path.write_text(md_content, encoding="utf-8")
    print(f"Generated test cases documentation at: {target_path}")


if __name__ == "__main__":
    main()
